import type { StoryChapter } from '../../domain/game';

const hardChapter = (
  id: string,
  title: string,
  location: string,
  theme: string,
  introduction: string,
  mapIcon: string,
  requirements: [number, number, number][],
  taskNames: [string, string, string],
  taskDescriptions: [string, string, string],
  baseReward: number,
  gemOnFinal = false,
): StoryChapter => ({
  id,
  title,
  location,
  theme,
  introduction,
  mapIcon,
  tasks: requirements.map(([driftwood, seaGlass, shell], index) => ({
    id: `${id}-task-${index + 1}`,
    title: taskNames[index],
    description: taskDescriptions[index],
    requirements: { driftwood, seaGlass, shell },
    reward: {
      coins: baseReward + index * 20,
      ...(gemOnFinal && index === 2 ? { gems: 1 } : {}),
    },
  })),
});

